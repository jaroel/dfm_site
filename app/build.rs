//! Static "responsive image" pipeline: resizes the sources in `assets/` to the
//! widths each page actually renders, content-hashes the filenames and writes
//! them to `public/assets/img/`, plus a manifest the app `include!`s.
//!
//! ponytail: no crate in the Leptos ecosystem does this (leptos_image is stuck
//! on Leptos 0.6), and cargo-leptos only hashes its own bundle output. This is
//! the smallest thing that produces `srcset` + immutable cache keys.

use std::fs;
use std::path::{Path, PathBuf};

use image::imageops::FilterType;
use image::ImageReader;
use sha2::{Digest, Sha256};

struct Source {
    /// const name in the generated manifest, e.g. `SPONSOR_MAKT`
    name: &'static str,
    /// source file, relative to the workspace root
    file: &'static str,
    /// widths to emit; the source width is always kept as the largest
    widths: &'static [u32],
}

